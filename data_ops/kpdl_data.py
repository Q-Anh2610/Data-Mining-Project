# =========================================================
# NORMALIZE ENTITY
# =========================================================

def normalize_entity(text):

    text = str(text)

    text = text.lower()

    text = unidecode(text)

    text = re.sub(
        r"[^a-z0-9 ]",
        "",
        text
    )

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text.strip()


# =========================================================
# CLEAN TEXT
# =========================================================

def clean_text(text):

    if pd.isna(text):
        return ""

    text = str(text)

    text = text.strip()

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text


# =========================================================
# MAP ENTITY LABEL
# =========================================================

def map_entity_label(label):

    label = label.upper()

    return LABEL_MAP.get(
        label,
        "OTHER"
    )


# =========================================================
# FIX ENTITY TYPE
# =========================================================

def fix_entity_type(entity, label):

    lower = normalize_entity(
        entity
    )

    if lower in PROGRAMMING_LANGUAGES:
        return "PROGRAMMING_LANGUAGE"

    if lower in FRAMEWORKS:
        return "FRAMEWORK"

    if lower in DATABASES:
        return "DATABASE"

    if lower in CLOUDS:
        return "CLOUD"

    if lower in MODELS:
        return "MODEL"

    if lower in TECH_TERMS:
        return "TECH"

    if lower in FOOD_WORDS:
        return "FOOD"

    if any(
        hint in lower
        for hint in LOCATION_HINTS
    ):
        return "LOCATION"

    if lower in KNOWN_LOCATIONS:
        return "LOCATION"

    return label


