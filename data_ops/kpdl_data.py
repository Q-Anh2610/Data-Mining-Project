# =========================================================
# INSERT ALIAS
# =========================================================

def insert_alias(

    entity_id,
    alias,
    language
):

    try:

        normalized_alias = normalize_entity(
            alias
        )

        existing = supabase.table(
            "knowledge_graph_aliases"
        ).select("id").eq(

            "normalized_alias",
            normalized_alias

        ).execute()

        if existing.data:
            return

        supabase.table(
            "knowledge_graph_aliases"
        ).insert({

            "entity_id": entity_id,

            "alias": alias,

            "normalized_alias":
            normalized_alias,

            "language": language

        }).execute()

    except Exception as e:

        print(
            "INSERT ALIAS ERROR"
        )

        print(e)


# =========================================================
# UPSERT ENTITY
# =========================================================

def upsert_entity(

    entity,
    entity_type,
    language,
    source_sentence,
    source
):

    normalized = normalize_entity(
        entity
    )

    # ==============================================
    # CACHE LOOKUP
    # ==============================================

    if normalized in entity_cache:

        existing = entity_cache[
            normalized
        ]

    else:

        existing = find_entity(
            normalized
        )

        if existing:

            entity_cache[
                normalized
            ] = existing

    # ==============================================
    # EXISTING ENTITY
    # ==============================================

    if existing:

        entity_id = existing["id"]

        update_frequency(

            entity_id,

            existing["frequency"]
        )

    # ==============================================
    # NEW ENTITY
    # ==============================================

    else:

        embedding = generate_embedding(
            entity
        )

        entity_id = create_entity(

            entity_name=entity,

            normalized_name=normalized,

            entity_type=entity_type,

            language=language,

            embedding=embedding,

            source=source
        )

        entity_cache[
            normalized
        ] = {

            "id": entity_id,

            "frequency": 1
        }

    # ==============================================
    # INSERT MENTION
    # ==============================================

    if entity_id:

        insert_mention(

            entity_id=entity_id,

            source_sentence=
            source_sentence,

            detected_label=
            entity_type,

            confidence=1.0,

            language=language
        )

    return entity_id


