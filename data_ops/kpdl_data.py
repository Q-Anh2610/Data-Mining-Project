# =========================================================
# RULE-BASED IT ENTITY EXTRACTION
# =========================================================

def extract_it_entities(text):

    entities = []

    lowered = text.lower()

    all_terms = (

        PROGRAMMING_LANGUAGES
        | FRAMEWORKS
        | DATABASES
        | CLOUDS
        | MODELS
        | TECH_TERMS
    )

    for term in all_terms:

        pattern = (
            r"\b"
            + re.escape(term.lower())
            + r"\b"
        )

        if re.search(
            pattern,
            lowered
        ):

            entities.append({

                "entity": term,

                "entity_type": fix_entity_type(
                    term,
                    "TECH"
                ),

                "confidence": 1.0
            })

    return entities


# =========================================================
# PROCESS TEXT
# =========================================================

def process_text(text):

    seen = set()

    entities = []

    try:

        ner_results = ner_pipeline(
            text
        )

        for item in ner_results:

            entity = item["word"]

            # ======================================
            # FIX WORDPIECE
            # ======================================

            entity = re.sub(
                r"^##",
                "",
                entity
            )


            entity = entity.strip()

            if not entity:
                continue
            if len(entity) <= 2:
                continue

            if entity.startswith("#"):
                continue

            # ======================================
            # FILTER SHORT ENTITY
            # ======================================

            if len(entity) <= 2:
                continue

            normalized = normalize_entity(
                entity
            )

            # ======================================
            # STOPWORDS
            # ======================================

            if normalized in STOPWORDS:
                continue

            # ======================================
            # DEDUP
            # ======================================

            if normalized in seen:
                continue

            seen.add(normalized)

            # ======================================
            # LABEL
            # ======================================

            label = item["entity_group"]

            confidence = float(
                item["score"]
            )

            if confidence < 0.7:
                continue

            label = map_entity_label(
                label
            )

            label = fix_entity_type(
                entity,
                label
            )

            entities.append({

                "entity": entity,

                "entity_type": label,

                "confidence": confidence
            })

        # ==========================================
        # RULE-BASED IT ENTITYS
        # ==========================================

        it_entities = extract_it_entities(
            text
        )

        for ent in it_entities:

            normalized = normalize_entity(
                ent["entity"]
            )

            if normalized in seen:
                continue

            seen.add(normalized)

            entities.append(ent)

    except Exception as e:

        print("PROCESS TEXT ERROR")
        print(e)

    return entities


# =========================================================
# FIND ENTITY
# =========================================================

def find_entity(normalized_name):

    try:

        response = supabase.table(
            "knowledge_graph_entities"
        ).select("*").eq(
            "normalized_name",
            normalized_name
        ).execute()

        if response.data:
            return response.data[0]

        return None

    except Exception as e:

        print("FIND ENTITY ERROR")
        print(e)

        return None


# =========================================================
# CREATE ENTITY
# =========================================================

def create_entity(

    entity_name,
    normalized_name,
    entity_type,
    language,
    embedding,
    source
):

    try:

        response = supabase.table(
            "knowledge_graph_entities"
        ).upsert({

            "entity_name": entity_name,

            "normalized_name": normalized_name,

            "entity_type": entity_type,

            "language": language,

            "frequency": 1,

            "preserve_in_translation": True,

            "is_translatable": False,

            "embedding": embedding,

            "source": source

        }).execute()

        print(
            f"INSERTED ENTITY: {entity_name}"
        )

        return response.data[0]["id"]

    except Exception as e:

        print("CREATE ENTITY ERROR")
        print(entity_name)
        print(e)

        return None


# =========================================================
# UPDATE FREQUENCY
# =========================================================

def update_frequency(

    entity_id,
    frequency
):

    try:

        supabase.table(
            "knowledge_graph_entities"
        ).update({

            "frequency":
            frequency + 1

        }).eq(

            "id",
            entity_id

        ).execute()

    except Exception as e:

        print(
            "UPDATE FREQUENCY ERROR"
        )

        print(e)


