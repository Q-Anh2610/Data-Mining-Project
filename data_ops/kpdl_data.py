# 1. Thống kê chỉ số độ dài (Mean, Max, Min)
def get_length_stats(df):
    stats = {
        'Metric': ['Mean length', 'Max length', 'Min length'],
        'English': [
            df['english_text'].str.split().str.len().mean(),
            df['english_text'].str.split().str.len().max(),
            df['english_text'].str.split().str.len().min()
        ],
        'Vietnamese': [
            df['vietnamese_text'].str.split().str.len().mean(),
            df['vietnamese_text'].str.split().str.len().max(),
            df['vietnamese_text'].str.split().str.len().min()
        ]
    }
    return pd.DataFrame(stats)

# 2. Thống kê các loại dữ liệu lỗi
def get_error_counts(df):
    # Dữ liệu thiếu
    missing = df[['english_text', 'vietnamese_text']].isnull().any(axis=1).sum()

    # Dữ liệu trùng lặp
    duplicates = df.duplicated(subset=['english_text', 'vietnamese_text']).sum()

    # Outliers dựa trên tỷ lệ độ dài (ví dụ: chênh lệch > 3 lần)
    en_len = df['english_text'].str.split().str.len()
    vi_len = df['vietnamese_text'].str.split().str.len()
    # Tránh chia cho 0 bằng cách cộng epsilon hoặc chỉ xét câu có độ dài > 0
    ratio = en_len / vi_len.replace(0, 1)
    outliers = ((ratio > 3) | (ratio < 1/3)).sum()

    error_stats = {
        'Loại dữ liệu': ['Missing values', 'Duplicate records', 'Outlier sentences'],
        'Số lượng': [missing, duplicates, outliers]
    }
    return pd.DataFrame(error_stats)

